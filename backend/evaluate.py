#!/usr/bin/env python3
"""
evaluate.py — Official Evaluation Benchmark for StockSentinel AI.

Evaluates detector precision@20 per store-day and recall against hidden ground truth labels.
In strict accordance with the official R1 Phantom Stock-Out Detector PDF:
- Input: Ranked Top-20 findings per store-day (without hidden labels)
- Ground Truth: Hidden binary labels marking real phantom stock-outs on ~3% of rows
- Output: Precision@20 per store-day, Overall Precision@20, and Recall
"""

import sys
import os
import json
import argparse
from datetime import datetime

# Add root directory to sys.path so backend imports resolve cleanly
current_dir = os.path.dirname(os.path.abspath(__file__))
parent_dir = os.path.dirname(current_dir)
if parent_dir not in sys.path:
    sys.path.insert(0, parent_dir)

from backend.app.db.database import SessionLocal, init_db
from backend.app.db.models import Finding, GroundTruthLabel, Store
from backend.app.db.repository import StockSentinelRepository
from backend.app.services.evaluation_service import EvaluationService


def run_evaluation(evaluation_date: str, output_format: str = "summary", dataset_id: str | None = None) -> dict:
    """
    Executes benchmark evaluation against hidden labels for the specified evaluation date and optional dataset_id.
    """
    init_db()
    db = SessionLocal()
    try:
        repo = StockSentinelRepository(db)
        
        # 1. Fetch hidden ground truth labels (completely held back from detector)
        gt_labels = repo.get_ground_truth_for_date(evaluation_date, dataset_id=dataset_id)
        if not gt_labels:
            print(f"[-] Error: No ground-truth labels found for date '{evaluation_date}' (dataset: {dataset_id or 'default/all'}).")
            available = repo.get_available_ground_truth_dates(dataset_id=dataset_id)
            if available:
                print(f"[*] Available ground-truth dates: {', '.join(available)}")
            else:
                print("[-] No ground-truth labels exist in the database. Run data seeding or import labels first.")
            return {"error": "no_ground_truth", "date": evaluation_date}

        # 2. Fetch top findings generated by detector for that date
        findings = repo.get_findings(evaluation_date=evaluation_date, dataset_id=dataset_id, limit=1000)
        if not findings:
            print(f"[*] No prior scan findings cached for '{evaluation_date}'. Running detection scan...")
            try:
                from backend.app.schemas.scan import ScanRequest
                from backend.app.api.scans import execute_scan
                execute_scan(ScanRequest(evaluation_date=evaluation_date, dataset_id=dataset_id, threshold_days=3), db=db)
                findings = repo.get_findings(evaluation_date=evaluation_date, dataset_id=dataset_id, limit=1000)
            except Exception as scan_err:
                print(f"[-] Scan execution failed: {scan_err}")
                return {"error": "scan_failed", "detail": str(scan_err)}

        if not findings:
            print(f"[-] Warning: No detector findings generated for date '{evaluation_date}' (dataset: {dataset_id or 'default/all'}).")
            return {"error": "no_findings", "date": evaluation_date}

        stores_map = {s.store_id: s.name for s in repo.get_all_stores(dataset_id=dataset_id)}

        # 3. Compute official benchmark metrics
        result = EvaluationService.evaluate_findings(
            findings=findings,
            ground_truth=gt_labels,
            evaluation_date=evaluation_date,
            store_names_map=stores_map,
        )

        res_dict = result.model_dump()
        if dataset_id:
            res_dict["dataset_id"] = dataset_id

        if output_format == "json":
            print(json.dumps(res_dict, indent=2))
        else:
            # Human-readable summary
            print("\n" + "=" * 70)
            print("  StockSentinel AI — Official Evaluation Report (evaluate.py)")
            print("  Benchmark: R1 The Phantom Stock-Out Detector")
            print("=" * 70)
            print(f" Evaluation Date           : {res_dict['evaluation_date']}")
            if dataset_id:
                print(f" Dataset ID                : {dataset_id}")
            print(f" Total Stores Evaluated    : {res_dict['total_stores_evaluated']}")
            print(f" Total Top-20 Checks       : {res_dict['total_findings_evaluated']}")
            print(f" True Positives Verified   : {res_dict['total_true_positives']}")
            print(f" Ground Truth Positives    : {res_dict['total_ground_truth_positives']}")
            print("-" * 70)
            print(f" >> Mean Precision@20      : {res_dict['mean_precision_at_20']}%")
            print(f" >> Overall Recall         : {res_dict['overall_recall']}%")
            print("-" * 70)
            print("\n Per-Store Breakdown:")
            print(f" {'Store ID':<12} | {'Store Name':<32} | {'Top20':<6} | {'TP':<4} | {'P@20':<8} | {'Recall':<8}")
            print("-" * 80)
            for sm in res_dict.get("per_store_metrics", []):
                s_name = (sm["store_name"] or sm["store_id"])[:32]
                print(
                    f" {sm['store_id']:<12} | {s_name:<32} | {sm['top20_findings_count']:<6} | "
                    f"{sm['true_positives_in_top20']:<4} | {sm['precision_at_20']:>5.1f}% | {sm['recall_at_20']:>5.1f}%"
                )
            print("=" * 70 + "\n")

        return res_dict
    finally:
        db.close()


def main():
    parser = argparse.ArgumentParser(description="Evaluate StockSentinel detector against hidden ground-truth labels.")
    parser.add_argument("--date", type=str, default=None, help="Evaluation date in YYYY-MM-DD format (default: benchmark date 2025-04-18)")
    parser.add_argument("--dataset-id", type=str, default=None, help="Optional dataset ID to isolate evaluation")
    parser.add_argument("--format", type=str, choices=["summary", "json"], default="summary", help="Output format (summary or json)")
    args = parser.parse_args()

    eval_date = args.date
    if not eval_date:
        from backend.app.db.database import SessionLocal, init_db
        from backend.app.db.repository import StockSentinelRepository
        init_db()
        db = SessionLocal()
        try:
            repo = StockSentinelRepository(db)
            available = repo.get_available_ground_truth_dates(dataset_id=args.dataset_id)
            if "2025-04-18" in available:
                eval_date = "2025-04-18"
            elif available:
                eval_date = available[-1]
            else:
                eval_date = "2025-04-18"
        finally:
            db.close()

    run_evaluation(evaluation_date=eval_date, output_format=args.format, dataset_id=args.dataset_id)


if __name__ == "__main__":
    main()

