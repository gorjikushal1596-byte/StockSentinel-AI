"""
Regression tests for Top-20 Queue verification-status persistence.

Verifies:
1. Updating a finding's status through PATCH /api/findings/{id}/status persists to the database.
2. Reloading/fetching the queue via GET /api/findings returns the updated status (does not revert to pending).
3. Re-executing a detection scan for the same store-day preserves previously verified associate statuses.
4. Transitions across all valid statuses (pending, unresolved, verified, false_positive).
5. Invalid status updates are rejected and do not corrupt persisted state.
"""

import pytest
from fastapi.testclient import TestClient
from app.main import app
from app.db.database import init_db, SessionLocal
from app.db.repository import StockSentinelRepository
from app.schemas.scan import ScanRequest
from app.api.scans import execute_scan

client = TestClient(app)


@pytest.fixture(scope="module")
def setup_scan_findings():
    """Initializes tables and executes a scan to generate deterministic findings."""
    init_db()
    db = SessionLocal()
    try:
        # Check if synthetic dataset exists; if not, seed data
        from app.services.dataset_service import DatasetService
        svc = DatasetService(db)
        datasets = svc.list_datasets()
        target_ds = next((d for d in datasets if (d.dataset_id.startswith("DS_SAFFRON") or d.dataset_id.startswith("DS_SYNTHETIC")) and d.status == "imported"), None)
        if not target_ds:
            target_ds, _ = svc.load_synthetic_dataset()

        eval_date = "2026-07-01"
        scan_res = execute_scan(
            ScanRequest(
                evaluation_date=eval_date,
                dataset_id=target_ds.dataset_id,
                threshold_days=3,
                max_findings_per_store=20,
            ),
            db=db,
        )
        return {
            "dataset_id": target_ds.dataset_id,
            "evaluation_date": eval_date,
            "scan_id": scan_res.scan_id,
            "findings": scan_res.findings,
        }
    finally:
        db.close()


def test_verification_status_update_and_reload_persistence(setup_scan_findings):
    """
    Changing a finding's status (e.g. to 'unresolved' / Floor Check Dispatched)
    persists in the database and remains saved when reloading the queue.
    """
    scan_info = setup_scan_findings
    eval_date = scan_info["evaluation_date"]
    dataset_id = scan_info["dataset_id"]
    findings = scan_info["findings"]

    assert len(findings) > 0, "Expected findings to be generated by scan"
    target_finding = findings[0]
    finding_id = target_finding.finding_id
    sku_id = target_finding.sku_id
    store_id = target_finding.store_id

    # 1. Update status to 'unresolved' (Floor Check Dispatched)
    patch_res = client.patch(
        f"/api/findings/{finding_id}/status",
        json={"status": "unresolved", "notes": "Dispatched floor associate for aisle check"},
    )
    assert patch_res.status_code == 200, f"Status patch failed: {patch_res.text}"
    updated_data = patch_res.json()
    assert updated_data["finding_id"] == finding_id
    assert updated_data["status"] == "unresolved"

    # 2. Verify direct database read-back
    db = SessionLocal()
    try:
        repo = StockSentinelRepository(db)
        db_finding = repo.get_finding(finding_id)
        assert db_finding is not None
        assert db_finding.status == "unresolved", f"Expected DB status 'unresolved', got '{db_finding.status}'"
    finally:
        db.close()

    # 3. Reload queue via GET /api/findings (simulating refreshing the browser)
    reload_res = client.get(f"/api/findings?date={eval_date}&dataset_id={dataset_id}&limit=100")
    assert reload_res.status_code == 200
    reloaded_findings = reload_res.json()
    assert len(reloaded_findings) > 0

    reloaded_target = next((f for f in reloaded_findings if f["finding_id"] == finding_id or (f["store_id"] == store_id and f["sku_id"] == sku_id)), None)
    assert reloaded_target is not None, f"Finding {finding_id} ({sku_id}) should be present in reloaded queue"
    assert reloaded_target["status"] == "unresolved", (
        f"Persisted status reverted! Expected 'unresolved', got '{reloaded_target['status']}'"
    )


def test_rescan_preserves_verified_status(setup_scan_findings):
    """
    Re-executing a detection scan for the same store-day MUST preserve
    previously confirmed associate statuses rather than resetting to 'pending'.
    """
    scan_info = setup_scan_findings
    eval_date = scan_info["evaluation_date"]
    dataset_id = scan_info["dataset_id"]

    # Pick a finding to mark as 'verified' (Resolved / Restocked)
    queue_res = client.get(f"/api/findings?date={eval_date}&dataset_id={dataset_id}&limit=50")
    queue = queue_res.json()
    assert len(queue) > 1

    finding_to_verify = queue[1]
    fid = finding_to_verify["finding_id"]
    sku_id = finding_to_verify["sku_id"]
    store_id = finding_to_verify["store_id"]

    # Mark as 'verified'
    patch_res = client.patch(
        f"/api/findings/{fid}/status",
        json={"status": "verified", "notes": "Restocked 10 units from backroom"},
    )
    assert patch_res.status_code == 200
    assert patch_res.json()["status"] == "verified"

    # Re-run a detection scan (simulating user clicking 'Run Backend Scan')
    rescan_res = client.post(
        "/api/scans",
        json={
            "evaluation_date": eval_date,
            "dataset_id": dataset_id,
            "threshold_days": 3,
            "max_findings_per_store": 20,
        },
    )
    assert rescan_res.status_code == 200
    new_scan = rescan_res.json()

    # The finding for (store_id, sku_id) in the new scan must carry forward 'verified'
    re_scanned_item = next(
        (f for f in new_scan["findings"] if f["store_id"] == store_id and f["sku_id"] == sku_id),
        None,
    )
    assert re_scanned_item is not None
    assert re_scanned_item["status"] == "verified", (
        f"Re-scan wiped associate verification! Expected 'verified', got '{re_scanned_item['status']}'"
    )

    # Reload queue and verify it remains 'verified'
    queue_after_rescan = client.get(f"/api/findings?date={eval_date}&dataset_id={dataset_id}&limit=50").json()
    item_in_queue = next(
        (f for f in queue_after_rescan if f["store_id"] == store_id and f["sku_id"] == sku_id),
        None,
    )
    assert item_in_queue is not None
    assert item_in_queue["status"] == "verified"


def test_invalid_status_rejected_without_corrupting_state(setup_scan_findings):
    """Sending an unaccepted status returns 400 and preserves existing status."""
    scan_info = setup_scan_findings
    findings = scan_info["findings"]
    fid = findings[0].finding_id

    # Current status
    initial_res = client.get(f"/api/findings/{fid}")
    assert initial_res.status_code == 200
    original_status = initial_res.json()["status"]

    # Attempt invalid status
    bad_res = client.patch(f"/api/findings/{fid}/status", json={"status": "bogus_status"})
    assert bad_res.status_code in (400, 422)

    # Verify status is untouched
    check_res = client.get(f"/api/findings/{fid}")
    assert check_res.json()["status"] == original_status
